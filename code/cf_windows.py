# Time intervals of the record pairs kept (KEEP) and excluded (EXCL) by station.
import pandas as pd

T = lambda s: pd.Timestamp(s, tz='UTC')

KEEP = {
    'HDB':  lambda t: t > T('2019-03-01'),
    'HSB':  lambda t: t > T('2018-11-01'),
    'HAMB': lambda t: t > T('2017-09-01'),
    'ULDR': lambda t: (t < T('2020-12-31')) | (t > T('2023-01-01')),
    'MGB':  lambda t: (t < T('2019-01-01')) | (t > T('2019-11-30')),
    'JRB':  lambda t: (t < T('2018-01-01')) | (t > T('2018-06-01')),
    'HANB': lambda t: (t < T('2020-05-15')) | (t > T('2023-01-01')),
    'ECDB': lambda t: t < T('2022-04-01'),
    'OYDB': lambda t: t < T('2022-04-01'),
    'NAWB': lambda t: (t < T('2019-01-01')) | (t > T('2020-01-01')),
    'GWYB': lambda t: (t < T('2018-12-31')) | (t > T('2019-07-01')),
    'GAHB': lambda t: (t < T('2016-03-30')) | ((t > T('2017-06-01')) & (t < T('2017-12-31'))),
    'GMHB': lambda t: (t < T('2020-06-01')) | (t > T('2022-04-01')),
    'GAPB': lambda t: (t < T('2018-11-01')) | ((t > T('2019-04-01')) & (t < T('2019-09-01'))) | (t > T('2020-05-01')),
    'SHHB': lambda t: (t < T('2020-01-01')) | ((t > T('2020-09-01')) & (t < T('2020-12-31'))),
    'OKCB': lambda t: (t < T('2019-04-01')) | ((t > T('2019-10-01')) & (t < T('2020-04-01'))) | (t > T('2020-11-01')),
    'YOCB': lambda t: (t < T('2017-06-01')) | (t > T('2018-05-01')),
    'YKDB': lambda t: (t < T('2020-02-01')) | (t > T('2022-02-28')),
    'YNCB': lambda t: ((t > T('2017-03-01')) & (t < T('2018-01-01'))) | (t > T('2018-06-01')),
    'YNDB': lambda t: (t < T('2018-11-01')) | ((t > T('2019-09-01')) & (t < T('2021-12-31'))),
    'YODB': lambda t: (t < T('2019-09-01')) | (t > T('2021-01-01')),
    'YPDB': lambda t: (t < T('2020-07-01')) | (t > T('2022-04-01')),
    'PYDB': lambda t: (t < T('2019-09-01')) | (t > T('2020-04-01')),
    'PYCB': lambda t: (t < T('2019-09-01')) | (t > T('2020-04-01')),
    'IMWB': lambda t: (t < T('2017-10-01')) | (t > T('2019-02-28')),
    'MOPB': lambda t: t < T('2022-07-01'),
    'HA2B': lambda t: ((t > T('2021-07-01')) & (t < T('2021-11-30'))) | ((t > T('2022-01-01')) & (t < T('2022-06-30'))) | (t > T('2022-09-01')),
    'JEJB': lambda t: pd.Series(False, index=t.index),
}
EXCL = {
    'HDB': 'before 2019-03-01', 'HSB': 'before 2018-11-01', 'HAMB': 'before 2017-09-01',
    'ULDR': '2020-12-31 to 2023-01-01', 'MGB': '2019-01-01 to 2019-11-30', 'JRB': '2018-01-01 to 2018-06-01',
    'HANB': '2020-05-15 to 2023-01-01', 'ECDB': 'after 2022-04-01', 'OYDB': 'after 2022-04-01',
    'NAWB': '2019-01-01 to 2020-01-01', 'GWYB': '2018-12-31 to 2019-07-01',
    'GAHB': '2016-03-30 to 2017-06-01 and after 2017-12-31', 'GMHB': '2020-06-01 to 2022-04-01',
    'GAPB': '2018-11-01 to 2019-04-01 and 2019-09-01 to 2020-05-01', 'SHHB': '2020-01-01 to 2020-09-01 and after 2020-12-31',
    'OKCB': '2019-04-01 to 2019-10-01 and 2020-04-01 to 2020-11-01', 'YOCB': '2017-06-01 to 2018-05-01',
    'YKDB': '2020-02-01 to 2022-02-28', 'YNCB': 'before 2017-03-01 and 2018-01-01 to 2018-06-01',
    'YNDB': '2018-11-01 to 2019-09-01 and after 2021-12-31', 'YODB': '2019-09-01 to 2021-01-01',
    'YPDB': '2020-07-01 to 2022-04-01', 'PYDB': '2019-09-01 to 2020-04-01', 'PYCB': '2019-09-01 to 2020-04-01',
    'IMWB': '2017-10-01 to 2019-02-28', 'MOPB': 'after 2022-07-01',
    'HA2B': 'before 2021-07-01, 2021-11-30 to 2022-01-01, and 2022-06-30 to 2022-09-01', 'JEJB': 'all records',
}
